// Compiles the vendored Lucide SVGs into a plain JS module.
//
// The design system has no build step and no npm dependencies — it is JSX that
// any bundler can consume — so `Icon` cannot use `import.meta.glob` or a
// bundler's asset loader without giving that up. A generated module is the one
// form that works everywhere and needs nothing at runtime.
//
// Run after adding an SVG: node assets/icons/build.mjs
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

const files = (await readdir(here)).filter((f) => f.endsWith('.svg')).sort();

const entries = [];
for (const file of files) {
  const raw = await readFile(join(here, file), 'utf8');

  // Keep only what goes inside the <svg>: the paths. The wrapper's size,
  // viewBox and stroke width are the component's to decide.
  const inner = raw
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .replace(/\s+/g, ' ')
    .trim();

  entries.push(`  '${file.replace(/\.svg$/, '')}': '${inner.replace(/'/g, "\\'")}',`);
}

await writeFile(
  join(here, 'index.js'),
  `// Generated by assets/icons/build.mjs. Do not edit.
//
// Lucide ${files.length} icons, ISC licensed, vendored so that the console works
// without network access — an installation on a private network is a normal way
// to run Pando, and icons fetched from a CDN at runtime simply do not appear
// there. The brand spec asked for this: "for production or offline use, vendor
// the icons you actually use into assets/icons/ and point Icon at them."
//
// Add one by dropping its SVG beside this file and re-running the script.

export const icons = {
${entries.join('\n')}
};
`,
);

console.log(`compiled ${files.length} icons`);
